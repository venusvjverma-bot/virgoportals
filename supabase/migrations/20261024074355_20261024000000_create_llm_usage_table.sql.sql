/*
# Create llm_usage table for per-request LLM token tracking

1. New Tables
- `llm_usage`
  - `id` (uuid, primary key, auto-generated)
  - `restaurant_id` (uuid, foreign key to restaurants.id, not null)
  - `input_tokens` (integer, not null, default 0) — tokens consumed by the prompt sent to the LLM
  - `output_tokens` (integer, not null, default 0) — tokens generated by the LLM in its response
  - `created_at` (timestamptz, not null, default now()) — when the LLM request was made

2. Indexes
- `idx_llm_usage_restaurant_id` on `restaurant_id` — speeds up per-host aggregation queries
- `idx_llm_usage_created_at` on `created_at` — speeds up time-range and recent-usage queries

3. Security (RLS)
- Enable RLS on `llm_usage`.
- Grant SELECT, INSERT, UPDATE, DELETE to `authenticated` and `service_role`.
  - `authenticated`: hosts and admins access through RLS policies.
  - `service_role`: edge functions insert rows using the service role key (bypasses RLS but needs the grant).
- SELECT policy: admin or the restaurant owner can read their own rows (matches usage_events pattern using `is_admin()` and `owns_restaurant()`).
- INSERT policy: admin or restaurant owner can insert.
- UPDATE policy: admin or restaurant owner can update.
- DELETE policy: admin only (matches usage_events delete pattern).

4. Important Notes
- This migration creates the table only. No edge functions are modified.
- The table will be populated by future changes to the visitor-chat, menu-extract, and dish-image edge functions.
- RLS policies follow the same `is_admin()` / `owns_restaurant()` helper pattern used by `usage_events`.
*/

CREATE TABLE IF NOT EXISTS llm_usage (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  restaurant_id uuid NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  input_tokens integer NOT NULL DEFAULT 0,
  output_tokens integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE llm_usage ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON llm_usage TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON llm_usage TO service_role;

CREATE INDEX IF NOT EXISTS idx_llm_usage_restaurant_id ON llm_usage(restaurant_id);
CREATE INDEX IF NOT EXISTS idx_llm_usage_created_at ON llm_usage(created_at);

DROP POLICY IF EXISTS "host_select_own_llm_usage" ON llm_usage;
CREATE POLICY "host_select_own_llm_usage"
  ON llm_usage FOR SELECT
  TO authenticated
  USING (is_admin() OR owns_restaurant(restaurant_id));

DROP POLICY IF EXISTS "host_insert_own_llm_usage" ON llm_usage;
CREATE POLICY "host_insert_own_llm_usage"
  ON llm_usage FOR INSERT
  TO authenticated
  WITH CHECK (is_admin() OR owns_restaurant(restaurant_id));

DROP POLICY IF EXISTS "host_update_own_llm_usage" ON llm_usage;
CREATE POLICY "host_update_own_llm_usage"
  ON llm_usage FOR UPDATE
  TO authenticated
  USING (is_admin() OR owns_restaurant(restaurant_id))
  WITH CHECK (is_admin() OR owns_restaurant(restaurant_id));

DROP POLICY IF EXISTS "admin_delete_llm_usage" ON llm_usage;
CREATE POLICY "admin_delete_llm_usage"
  ON llm_usage FOR DELETE
  TO authenticated
  USING (is_admin());
