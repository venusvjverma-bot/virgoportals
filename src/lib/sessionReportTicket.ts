import { jsPDF } from 'jspdf';
import { formatMinor } from '@/lib/currency';

export interface SessionReportOrder {
  orderNumber: string;
  paymentType: string;
  amountMinor: number;
  currency: string;
}

export interface SessionReportTicketData {
  restaurantName: string;
  departmentName: string;
  startedAt: string;
  closedAt: string;
  durationMinutes: number;
  orderCount: number;
  totalMinor: number;
  currency: string;
  paymentTotals: Record<string, number>;
  orders: SessionReportOrder[];
}

function dateValue(value: string): string {
  return new Date(value).toLocaleDateString();
}

function timeValue(value: string): string {
  return new Date(value).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
}

function durationValue(minutes: number): string {
  const hours = Math.floor(minutes / 60);
  const remaining = minutes % 60;
  return hours > 0 ? `${hours}h ${remaining}m` : `${remaining}m`;
}

function drawWrapped(doc: jsPDF, text: string, x: number, y: number, width: number, lineHeight: number): number {
  const lines = doc.splitTextToSize(text, width) as string[];
  for (const line of lines) {
    doc.text(line, x, y);
    y += lineHeight;
  }
  return y;
}

function drawReport(doc: jsPDF, report: SessionReportTicketData): number {
  const pageWidth = 80;
  const margin = 5;
  const contentWidth = pageWidth - margin * 2;
  const right = pageWidth - margin;
  let y = 7;

  const separator = () => {
    doc.setDrawColor(0, 0, 0);
    doc.setLineWidth(0.2);
    doc.line(margin, y, right, y);
  };

  doc.setTextColor(0, 0, 0);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('VIRGO PORTAL', pageWidth / 2, y, { align: 'center' });
  y += 5.5;
  doc.setFontSize(10);
  y = drawWrapped(doc, report.restaurantName, margin, y, contentWidth, 4.2);
  doc.setFontSize(10);
  y = drawWrapped(doc, report.departmentName, margin, y, contentWidth, 4.2);
  y += 1;
  doc.setFontSize(11);
  doc.text('CLOSED SESSION REPORT', pageWidth / 2, y, { align: 'center' });
  y += 5;
  separator();
  y += 4;

  const row = (label: string, value: string) => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.5);
    doc.text(label, margin, y);
    doc.setFont('helvetica', 'bold');
    doc.text(value, right, y, { align: 'right' });
    y += 4.2;
  };

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.text('SESSION DETAILS', margin, y);
  y += 4.5;
  row('Start date', dateValue(report.startedAt));
  row('Start time', timeValue(report.startedAt));
  row('Close date', dateValue(report.closedAt));
  row('Close time', timeValue(report.closedAt));
  row('Duration', durationValue(report.durationMinutes));
  y += 1;
  separator();
  y += 4;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.text('SESSION SUMMARY', margin, y);
  y += 4.5;
  row('Total orders', String(report.orderCount));
  row('Total sales', formatMinor(report.totalMinor, report.currency));
  y += 1;
  separator();
  y += 4;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.text('PAYMENT TOTALS', margin, y);
  y += 4.5;
  const paymentEntries = Object.entries(report.paymentTotals);
  for (const [paymentType, amountMinor] of paymentEntries) {
    row(paymentType, formatMinor(amountMinor, report.currency));
  }
  y += 1;
  separator();
  y += 4;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.text('ORDER DETAILS', margin, y);
  y += 4.5;
  for (const order of report.orders) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    y = drawWrapped(doc, order.orderNumber, margin, y, contentWidth - 20, 3.8);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.8);
    y = drawWrapped(doc, order.paymentType, margin + 2, y, contentWidth - 4, 3.5);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.text(formatMinor(order.amountMinor, order.currency), right, y - 3.5, { align: 'right' });
    y += 1.5;
    separator();
    y += 3.5;
  }

  y += 1;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text('END OF SESSION REPORT', pageWidth / 2, y, { align: 'center' });
  y += 4.5;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.text('Generated by Virgo Portal', pageWidth / 2, y, { align: 'center' });
  return y + 5;
}

export function generateSessionReportBlob(report: SessionReportTicketData): Blob {
  const measureDoc = new jsPDF({ unit: 'mm', format: [80, 600] });
  const height = Math.ceil(drawReport(measureDoc, report) + 4);
  const doc = new jsPDF({ unit: 'mm', format: [80, height] });
  drawReport(doc, report);
  return doc.output('blob');
}
